"""Python code emitter for Mini COBOL supporting standard and vectorized targets."""

from __future__ import annotations

from typing import List, Optional, Set

from src.ast_nodes import (
    AddStmtNode,
    DisplayStmtNode,
    ExprNode,
    IdentifierNode,
    MoveStmtNode,
    NumberLiteralNode,
    ParallelPerformStmtNode,
    ProgramNode,
    StatementNode,
    StringLiteralNode,
    VarDeclNode,
)
from src.symbol_table import Symbol, SymbolTable


def sanitize_ident(name: str) -> str:
    """Sanitize COBOL identifier into valid Python variable name."""
    return name.lower().replace("-", "_")


class CodeGenerator:
    """Python code emitter for Mini COBOL supporting standard and vectorized backends."""

    def __init__(
        self,
        ast: ProgramNode,
        symbol_table: SymbolTable,
        target: str = "standard",
    ) -> None:
        self.ast = ast
        self.symbol_table = symbol_table
        self.target = target.lower()
        if self.target not in ("standard", "vectorized"):
            raise ValueError(f"Unknown target backend: {target!r}. Must be 'standard' or 'vectorized'.")
        self.lines: List[str] = []
        self.indent_level = 0
        self.in_parallel_loop = False
        self.parallel_batch_vars: Set[str] = set()

    def _indent(self) -> str:
        return "    " * self.indent_level

    def _emit(self, line: str = "") -> None:
        if line:
            self.lines.append(f"{self._indent()}{line}")
        else:
            self.lines.append("")

    def generate(self) -> str:
        """Generate fully runnable, independent Python script."""
        self.lines = []
        self.indent_level = 0

        # Scan AST to detect batch variables used inside PERFORM ... IN PARALLEL
        self._detect_parallel_vars()

        self._emit_header()
        self._emit_runtime_helpers()
        self._emit_main_function()
        self._emit_entrypoint()

        return "\n".join(self.lines) + "\n"

    def emit_to_file(self, output_path: str = "runnable.py") -> None:
        """Generate and write code to the specified file."""
        code = self.generate()
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(code)

    def _detect_parallel_vars(self) -> None:
        """Identify which variables are modified or read inside parallel perform blocks."""
        for stmt in self.ast.statements:
            if isinstance(stmt, ParallelPerformStmtNode):
                for body_stmt in stmt.body:
                    if isinstance(body_stmt, MoveStmtNode):
                        self.parallel_batch_vars.add(body_stmt.target.name.upper())
                    elif isinstance(body_stmt, AddStmtNode):
                        self.parallel_batch_vars.add(body_stmt.target.name.upper())

    def _emit_header(self) -> None:
        self._emit("#!/usr/bin/env python3")
        self._emit('"""')
        self._emit(f"Production runnable script generated by Mini COBOL Transpiler.")
        self._emit(f"Target Backend: {self.target.upper()}")
        self._emit('"""')
        self._emit()
        self._emit("import argparse")
        self._emit("import os")
        self._emit("import sys")
        self._emit("import time")
        if self.target == "vectorized":
            self._emit("import numpy as np")
        self._emit()

    def _emit_runtime_helpers(self) -> None:
        """Emit formatting and fixed-point helper functions."""
        self._emit("# ----------------------------------------------------------------------")
        self._emit("# Runtime Fixed-Point & Output Formatting Helpers")
        self._emit("# ----------------------------------------------------------------------")
        self._emit("def format_fixed(val, scale_factor=100, decimals=2):")
        self._emit("    '''Format scaled integer into decimal string or batch summary.'''")
        if self.target == "vectorized":
            self._emit("    if isinstance(val, np.ndarray):")
            self._emit("        count = len(val)")
            self._emit("        if count == 0:")
            self._emit("            return '[]'")
            self._emit("        if decimals == 0:")
            self._emit("            first_5 = [str(x) for x in val[:5]]")
            self._emit("            total = int(val.sum())")
            self._emit("            return f'[Batch: {count:,} items | First 5: {first_5} | Sum: {total}]'")
            self._emit("        else:")
            self._emit("            first_5 = [f'{x / scale_factor:.{decimals}f}' for x in val[:5]]")
            self._emit("            total = float(val.sum()) / scale_factor")
            self._emit("            return f'[Batch: {count:,} items | First 5: {first_5} | Sum: {total:.{decimals}f}]'")
        self._emit("    if isinstance(val, list):")
        self._emit("        count = len(val)")
        self._emit("        if count == 0:")
        self._emit("            return '[]'")
        self._emit("        if decimals == 0:")
        self._emit("            first_5 = [str(x) for x in val[:5]]")
        self._emit("            total = sum(val)")
        self._emit("            return f'[Batch: {count:,} items | First 5: {first_5} | Sum: {total}]'")
        self._emit("        else:")
        self._emit("            first_5 = [f'{x / scale_factor:.{decimals}f}' for x in val[:5]]")
        self._emit("            total = sum(val) / scale_factor")
        self._emit("            return f'[Batch: {count:,} items | First 5: {first_5} | Sum: {total:.{decimals}f}]'")
        self._emit("    # Scalar integer value")
        self._emit("    if decimals == 0:")
        self._emit("        return str(val)")
        self._emit("    sign = '-' if val < 0 else ''")
        self._emit("    abs_v = abs(int(val))")
        self._emit("    int_p = abs_v // scale_factor")
        self._emit("    frac_p = abs_v % scale_factor")
        self._emit("    return f'{sign}{int_p}.{frac_p:0{decimals}d}'")
        self._emit()

    def _emit_main_function(self) -> None:
        self._emit("def run(data_path=None, benchmark=False):")
        self.indent_level += 1
        self._emit("'''Main program execution logic.'''")
        self._emit("wall_start = time.perf_counter()")
        self._emit()

        # Variable Declarations and Initialization
        self._emit("# --- Variable Storage (Scaled-Integer Representation) ---")
        for decl in self.ast.declarations:
            py_name = sanitize_ident(decl.name)
            is_parallel_var = decl.name.upper() in self.parallel_batch_vars

            if is_parallel_var:
                if self.target == "vectorized":
                    self._emit(f"# Batch variable: {decl.name} (PIC {decl.pic_spec}, scale={decl.scale_factor})")
                    self._emit(f"if data_path and os.path.exists(data_path):")
                    self._emit(f"    if data_path.endswith('.bin'):")
                    self._emit(f"        {py_name} = np.fromfile(data_path, dtype=np.int64)")
                    self._emit(f"    else:")
                    self._emit(f"        {py_name} = np.loadtxt(data_path, dtype=np.int64, delimiter=',')")
                    self._emit(f"else:")
                    self._emit(f"    # Default initial array (will be sized by parallel loop count)")
                    self._emit(f"    {py_name} = np.zeros(0, dtype=np.int64)")
                else:
                    self._emit(f"# Batch variable: {decl.name} (PIC {decl.pic_spec}, scale={decl.scale_factor})")
                    self._emit(f"if data_path and os.path.exists(data_path):")
                    self._emit(f"    if data_path.endswith('.bin'):")
                    self._emit(f"        import array")
                    self._emit(f"        arr = array.array('q')")
                    self._emit(f"        with open(data_path, 'rb') as f:")
                    self._emit(f"            arr.fromfile(f, os.path.getsize(data_path) // 8)")
                    self._emit(f"        {py_name} = list(arr)")
                    self._emit(f"    else:")
                    self._emit(f"        with open(data_path, 'r') as f:")
                    self._emit(f"            {py_name} = [int(line.strip().split(',')[0]) for line in f if line.strip()]")
                    self._emit(f"else:")
                    self._emit(f"    {py_name} = []")
            else:
                self._emit(f"{py_name} = 0  # PIC {decl.pic_spec}, scale={decl.scale_factor}")

        self._emit()
        self._emit("# --- Executable Statements ---")

        for stmt in self.ast.statements:
            self._emit_statement(stmt)

        self._emit()
        self._emit("wall_end = time.perf_counter()")
        self._emit("elapsed_sec = wall_end - wall_start")
        self._emit(f"if benchmark:")
        target_str = self.target.upper()
        self._emit(f"    print(f'\\n[BENCHMARK] Target: {target_str} | Wall Time: {{elapsed_sec * 1000:.3f}} ms ({{elapsed_sec:.6f}} s)')")
        self._emit()

        # Collect return dict for testing or benchmarking
        return_items = [f"'{sanitize_ident(d.name)}': {sanitize_ident(d.name)}" for d in self.ast.declarations]
        self._emit(f"return {{{', '.join(return_items)}}}, elapsed_sec")

        self.indent_level -= 1
        self._emit()

    def _emit_statement(self, stmt: StatementNode) -> None:
        if isinstance(stmt, MoveStmtNode):
            self._emit_move(stmt)
        elif isinstance(stmt, AddStmtNode):
            self._emit_add(stmt)
        elif isinstance(stmt, DisplayStmtNode):
            self._emit_display(stmt)
        elif isinstance(stmt, ParallelPerformStmtNode):
            self._emit_parallel_perform(stmt)

    def _emit_move(self, stmt: MoveStmtNode) -> None:
        target_name = stmt.target.name.upper()
        target_py = sanitize_ident(target_name)
        target_sym = self.symbol_table.require(
            target_name, stmt.target.line, stmt.target.col, len(target_name)
        )
        target_scale = target_sym.scale_factor

        is_batch_target = (not self.in_parallel_loop) and (target_name in self.parallel_batch_vars)

        if isinstance(stmt.source, NumberLiteralNode):
            scaled_val = stmt.source.scaled_value * (target_scale // stmt.source.scale_factor)
            if is_batch_target:
                if self.target == "vectorized":
                    self._emit(f"if len({target_py}) > 0:")
                    self._emit(f"    {target_py}.fill({scaled_val})")
                    self._emit(f"else:")
                    self._emit(f"    {target_py} = np.array([{scaled_val}], dtype=np.int64)")
                else:
                    self._emit(f"if len({target_py}) > 0:")
                    self._emit(f"    {target_py} = [{scaled_val}] * len({target_py})")
                    self._emit(f"else:")
                    self._emit(f"    {target_py} = [{scaled_val}]")
            else:
                self._emit(f"{target_py} = {scaled_val}")

        elif isinstance(stmt.source, StringLiteralNode):
            self._emit(f"{target_py} = {stmt.source.value!r}")

        elif isinstance(stmt.source, IdentifierNode):
            src_name = stmt.source.name.upper()
            src_py = sanitize_ident(src_name)
            src_sym = self.symbol_table.require(
                src_name, stmt.source.line, stmt.source.col, len(src_name)
            )
            src_scale = src_sym.scale_factor

            # Handle scale alignment
            expr = src_py
            if target_scale > src_scale:
                factor = target_scale // src_scale
                expr = f"({src_py} * {factor})"
            elif target_scale < src_scale:
                factor = src_scale // target_scale
                expr = f"({src_py} // {factor})"

            if is_batch_target:
                if self.target == "vectorized":
                    self._emit(f"{target_py} = np.copy({expr}) if isinstance({expr}, np.ndarray) else np.full_like({target_py}, {expr})")
                else:
                    self._emit(f"{target_py} = list({expr}) if isinstance({expr}, list) else [{expr}] * max(1, len({target_py}))")
            else:
                self._emit(f"{target_py} = {expr}")

    def _emit_add(self, stmt: AddStmtNode) -> None:
        target_name = stmt.target.name.upper()
        target_py = sanitize_ident(target_name)
        target_sym = self.symbol_table.require(
            target_name, stmt.target.line, stmt.target.col, len(target_name)
        )
        target_scale = target_sym.scale_factor

        # Helper to compute scaled operand expression
        def operand_expr(op: ExprNode) -> str:
            if isinstance(op, NumberLiteralNode):
                scaled = op.scaled_value * (target_scale // op.scale_factor)
                return str(scaled)
            elif isinstance(op, IdentifierNode):
                op_sym = self.symbol_table.require(
                    op.name.upper(), op.line, op.col, len(op.name)
                )
                op_py = sanitize_ident(op.name)
                if target_scale > op_sym.scale_factor:
                    factor = target_scale // op_sym.scale_factor
                    return f"({op_py} * {factor})"
                elif target_scale < op_sym.scale_factor:
                    factor = op_sym.scale_factor // target_scale
                    return f"({op_py} // {factor})"
                return op_py
            return "0"

        if stmt.has_giving:
            # ADD op1 TO op2 GIVING target.
            op1_expr = operand_expr(stmt.operand1)
            op2_expr = operand_expr(stmt.operand2)  # type: ignore
            self._emit(f"{target_py} = {op1_expr} + {op2_expr}")
        else:
            # ADD op1 TO target.
            op1_expr = operand_expr(stmt.operand1)
            self._emit(f"{target_py} += {op1_expr}")

    def _emit_display(self, stmt: DisplayStmtNode) -> None:
        """Emit print statement formatting strings and scaled values."""
        format_parts: List[str] = []
        for item in stmt.items:
            if isinstance(item, StringLiteralNode):
                format_parts.append(f"{item.value!r}")
            elif isinstance(item, NumberLiteralNode):
                format_parts.append(f"{item.raw!r}")
            elif isinstance(item, IdentifierNode):
                sym = self.symbol_table.require(
                    item.name.upper(), item.line, item.col, len(item.name)
                )
                py_name = sanitize_ident(item.name)
                format_parts.append(
                    f"format_fixed({py_name}, scale_factor={sym.scale_factor}, decimals={sym.decimals})"
                )

        if len(format_parts) == 1:
            self._emit(f"print({format_parts[0]})")
        else:
            args_joined = ", ".join(format_parts)
            self._emit(f"print({args_joined}, sep='')")

    def _emit_parallel_perform(self, stmt: ParallelPerformStmtNode) -> None:
        """Emit parallel batch execution."""
        if isinstance(stmt.count, NumberLiteralNode):
            count_expr = str(int(stmt.count.raw))
        elif isinstance(stmt.count, IdentifierNode):
            count_expr = sanitize_ident(stmt.count.name)
        else:
            count_expr = "1000"

        self._emit(f"# --- Parallel Batch Block: PERFORM {count_expr} TIMES IN PARALLEL ---")
        self._emit(f"_batch_n = {count_expr}")

        # Ensure batch variables are initialized to size _batch_n if not loaded from file
        for var_name in self.parallel_batch_vars:
            py_var = sanitize_ident(var_name)
            sym = self.symbol_table.lookup(var_name)
            scale = sym.scale_factor if sym else 100

            if self.target == "vectorized":
                self._emit(f"if len({py_var}) != _batch_n:")
                self._emit(f"    # Allocate contiguous SIMD array of size {count_expr} with base scale {scale}")
                self._emit(f"    {py_var} = np.full(_batch_n, 100000, dtype=np.int64) if len({py_var}) == 0 else np.resize({py_var}, _batch_n)")
            else:
                self._emit(f"if len({py_var}) != _batch_n:")
                self._emit(f"    {py_var} = [100000] * _batch_n if len({py_var}) == 0 else ({py_var} * ((_batch_n // max(1, len({py_var}))) + 1))[:_batch_n]")

        if self.target == "vectorized":
            # Vectorized execution: Emit SIMD array operations directly without python loop!
            self._emit("# SIMD Vectorized Execution: Direct NumPy vector operations")
            for body_stmt in stmt.body:
                self._emit_statement(body_stmt)
        else:
            # Standard execution: Emit standard Python iterative loop
            self._emit("# Standard Execution: Python iterative loop")
            # To simulate element-by-element standard loop over the accounts:
            primary_var = sanitize_ident(list(self.parallel_batch_vars)[0]) if self.parallel_batch_vars else None
            if primary_var:
                self._emit(f"for _i in range(len({primary_var})):")
                self.indent_level += 1
                for body_stmt in stmt.body:
                    if isinstance(body_stmt, AddStmtNode):
                        t_py = sanitize_ident(body_stmt.target.name)
                        t_sym = self.symbol_table.require(
                            body_stmt.target.name.upper(), body_stmt.target.line, body_stmt.target.col, len(body_stmt.target.name)
                        )
                        t_scale = t_sym.scale_factor
                        if isinstance(body_stmt.operand1, NumberLiteralNode):
                            scaled_val = body_stmt.operand1.scaled_value * (t_scale // body_stmt.operand1.scale_factor)
                            if body_stmt.has_giving:
                                pass
                            else:
                                self._emit(f"{t_py}[_i] += {scaled_val}")
                        elif isinstance(body_stmt.operand1, IdentifierNode):
                            op_sym = self.symbol_table.require(
                                body_stmt.operand1.name.upper(), body_stmt.operand1.line, body_stmt.operand1.col, len(body_stmt.operand1.name)
                            )
                            op_py = sanitize_ident(body_stmt.operand1.name)
                            factor = t_scale // op_sym.scale_factor if t_scale >= op_sym.scale_factor else 1
                            scale_mul = f" * {factor}" if factor > 1 else ""
                            if body_stmt.operand1.name.upper() in self.parallel_batch_vars:
                                self._emit(f"{t_py}[_i] += {op_py}[_i]{scale_mul}")
                            else:
                                self._emit(f"{t_py}[_i] += {op_py}{scale_mul}")
                    elif isinstance(body_stmt, MoveStmtNode):
                        t_py = sanitize_ident(body_stmt.target.name)
                        if isinstance(body_stmt.source, NumberLiteralNode):
                            self._emit(f"{t_py}[_i] = {body_stmt.source.scaled_value}")
                        elif isinstance(body_stmt.source, IdentifierNode):
                            s_py = sanitize_ident(body_stmt.source.name)
                            if body_stmt.source.name.upper() in self.parallel_batch_vars:
                                self._emit(f"{t_py}[_i] = {s_py}[_i]")
                            else:
                                self._emit(f"{t_py}[_i] = {s_py}")
                self.indent_level -= 1
            else:
                self._emit(f"for _i in range(_batch_n):")
                self.indent_level += 1
                for body_stmt in stmt.body:
                    self._emit_statement(body_stmt)
                self.indent_level -= 1

        self._emit("# --- End Parallel Batch Block ---")

    def _emit_entrypoint(self) -> None:
        self._emit("def main():")
        self.indent_level += 1
        self._emit("parser = argparse.ArgumentParser(description='Mini COBOL Runnable Script')")
        self._emit("parser.add_argument('--data', type=str, default=None, help='Path to account balances binary or CSV file')")
        self._emit("parser.add_argument('--benchmark', action='store_true', help='Print wall-clock execution time')")
        self._emit("parser.add_argument('--verify', action='store_true', help='Verify output integrity')")
        self._emit("args = parser.parse_args()")
        self._emit()
        self._emit("# Auto-detect benchmark balances if no --data provided")
        self._emit("data_file = args.data")
        self._emit("if not data_file:")
        self._emit("    candidates = ['benchmark/balances.bin', 'balances.bin', 'benchmark/balances.csv', 'balances.csv']")
        self._emit("    for c in candidates:")
        self._emit("        if os.path.exists(c):")
        self._emit("            data_file = c")
        self._emit("            break")
        self._emit()
        self._emit("state, elapsed = run(data_path=data_file, benchmark=args.benchmark)")
        self._emit("sys.exit(0)")
        self.indent_level -= 1
        self._emit()
        self._emit("if __name__ == '__main__':")
        self._emit("    main()")
